"""Generate Dart constants for the Flutter app from the web app's JSON data.

Run from the repository root: python3 scripts/flutter/export_data.py
The JSON files in lib/ stay the single source of truth.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
lengths = json.loads((root / "lib/bible-lengths.json").read_text())
canon = json.loads((root / "lib/schlachter-canon.json").read_text())
editions = json.loads((root / "lib/edition-canon.json").read_text())
bible52 = json.loads((root / "lib/bible52.json").read_text())

def s(v):
    return json.dumps(v, ensure_ascii=False).replace("$", "\\$")

out = [
    "// GENERATED by scripts/flutter/export_data.py from lib/*.json. Do not edit.",
    "// ignore_for_file: lines_longer_than_80_chars",
    "",
    "class BookData {",
    "  final String name;",
    "  final String code;",
    "  final List<int> words;",
    "  const BookData(this.name, this.code, this.words);",
    "}",
    "",
    "const List<BookData> bibleBooks = [",
]
for b in lengths:
    out.append(f"  BookData({s(b['name'])}, {s(b['code'])}, {json.dumps(b['words'])}),")
out += ["];", "", "/// Independently checked Schlachter 2000 inventory (code, chapters).",
        "const List<(String, int)> schlachterCanon = ["]
for b in canon["books"]:
    out.append(f"  ({s(b['code'])}, {b['chapters']}),")
out += ["];", "", "/// Chapter counts per book for the other editions.",
        "const Map<String, List<int>> editionChapterCounts = {"]
for ed in ["kjv", "synodal", "ohienko"]:
    out.append(f"  {s(ed)}: {json.dumps([b[ed] for b in editions['books']])},")
out += ["};", "",
        f"const String bible52Title = {s(bible52['title'])};",
        f"const String bible52Attribution = {s(bible52['attribution'])};",
        f"const List<String> bible52Categories = {s(bible52['categories'])};",
        "const List<List<String>> bible52WeekRefs = ["]
for w in bible52["weeks"]:
    out.append(f"  {s(w)},")
out += ["];", ""]
assert [b["code"] for b in editions["books"]] == [b["code"] for b in lengths]
target = root / "bibelschul_app/lib/core/data.g.dart"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(out))
print("wrote", target.relative_to(root), sum(len(b["words"]) for b in lengths), "chapters")
