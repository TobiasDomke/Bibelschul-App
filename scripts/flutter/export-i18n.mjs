// Generate bibelschul_app/lib/i18n/strings.g.dart from the web app's i18n modules.
// Run from the repository root: node scripts/flutter/export-i18n.mjs
import { build } from "esbuild";
import { writeFile, mkdir } from "node:fs/promises";

await build({
  stdin: {
    contents: `
      export { text, bookNames } from "./lib/i18n.ts";
      export { planText } from "./lib/plan-i18n.ts";
      export { experienceText } from "./lib/experience-i18n.ts";
      export { bible52Text } from "./lib/bible52-i18n.ts";
      export { bookOrderText } from "./lib/book-order-i18n.ts";
      export { chapterCorrectionText } from "./lib/chapter-correction-i18n.ts";
      export { deadlineText } from "./lib/deadline-i18n.ts";
      export { readingTimeText } from "./lib/reading-time-i18n.ts";
      export { pushText } from "./lib/push-i18n.ts";`,
    resolveDir: ".",
    loader: "ts",
  },
  outfile: ".test-runtime/i18n-export.js",
  bundle: true,
  platform: "node",
  format: "esm",
});
const m = await import("../../.test-runtime/i18n-export.js");
const langs = ["de", "ru", "en", "uk"];
const spaces = {
  Main: (l) => m.text(l),
  Plan: (l) => m.planText(l),
  Experience: (l) => m.experienceText(l),
  Bible52: (l) => m.bible52Text(l),
  BookOrder: (l) => m.bookOrderText(l),
  ChapterCorrection: (l) => m.chapterCorrectionText[l],
  Deadline: (l) => m.deadlineText(l),
  ReadingTime: (l) => m.readingTimeText(l),
  Push: (l) => m.pushText(l),
};
const reserved = new Set("table hashCode toString runtimeType noSuchMethod abstract as assert async await break case catch class const continue covariant default deferred do dynamic else enum export extends extension external factory false final finally for function get hide if implements import in interface is late library mixin new null of on operator part required rethrow return set show static super switch sync this throw true try typedef var void while with yield".split(" "));
const ident = (k) => (reserved.has(k) ? k + "_" : k);
const str = (v) => JSON.stringify(v).replace(/\$/g, "\\$");
let out = "// GENERATED by scripts/flutter/export-i18n.mjs from lib/*-i18n.ts. Do not edit.\n// ignore_for_file: lines_longer_than_80_chars, constant_identifier_names, non_constant_identifier_names\n\nimport '../core/languages.dart';\n\n";
for (const [name, get] of Object.entries(spaces)) {
  const keys = [...new Set(langs.flatMap((l) => Object.keys(get(l))))].sort();
  for (const l of langs) {
    const v = get(l);
    for (const k of keys) {
      if (typeof v[k] !== "string") throw new Error(`${name}.${k} missing or not a string in ${l}`);
    }
  }
  out += `class ${name}Texts {\n  final Map<String, String> table;\n  const ${name}Texts(this.table);\n  String operator [](String key) => table[key] ?? key;\n`;
  for (const k of keys) out += `  String get ${ident(k)} => table[${str(k)}]!;\n`;
  out += "}\n\n";
  out += `const Map<Lang, ${name}Texts> ${name[0].toLowerCase() + name.slice(1)}Translations = {\n`;
  for (const l of langs) {
    const v = get(l);
    out += `  Lang.${l}: ${name}Texts({\n`;
    for (const k of keys) out += `    ${str(k)}: ${str(v[k])},\n`;
    out += "  }),\n";
  }
  out += "};\n\n";
}
out += "/// Book names per language; German uses the data file's names.\nconst Map<Lang, List<String>> bookNameTranslations = {\n";
for (const l of ["ru", "en", "uk"]) out += `  Lang.${l}: ${str(m.bookNames(l))},\n`;
out += "};\n";
await mkdir("bibelschul_app/lib/i18n", { recursive: true });
await writeFile("bibelschul_app/lib/i18n/strings.g.dart", out);
console.log("i18n namespaces:", Object.keys(spaces).join(", "));
