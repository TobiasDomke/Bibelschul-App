/// Texts of the reworked app screens (setup, today, plan, notes, statistics,
/// settings) and of reading groups. Missing keys fall back to German, so a
/// gap never shows a raw key; test/texts_test.dart checks that none is missing.
class UiTexts {
  const UiTexts(this.t);
  final Map<String, String> t;

  String operator [](String key) => t[key] ?? _de[key] ?? key;
}

UiTexts ui(Lang lang) => switch (lang) {
      Lang.de => const UiTexts(_de),
      Lang.en => const UiTexts(_en),
      Lang.ru => const UiTexts(_ru),
      Lang.uk => const UiTexts(_uk),
    };

/// All keys, for the completeness test.
Iterable<String> get uiTextKeys => _de.keys;

/// Every language's table, for the completeness test.
