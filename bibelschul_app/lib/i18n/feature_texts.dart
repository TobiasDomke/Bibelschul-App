/// Texts for features that exist only in the native app (notes, presets,
/// sharing plans, smart reminders, automatic backups, book overview ...).
class FeatureTexts {
  const FeatureTexts(this.t, this.questions);
  final Map<String, String> t;

  /// Reflection questions per text genre (see [genreOfBook]).
  final Map<String, List<String>> questions;

  String operator [](String key) => t[key] ?? key;
}

/// Text genre for reflection questions, by book index (0 = Genesis … 65 = Revelation).
String genreOfBook(int bookIndex) {
  if (bookIndex <= 4) return 'law';
  if (bookIndex <= 16) return 'history';
  if (bookIndex == 18) return 'psalms';
  if (bookIndex <= 21) return 'wisdom';
  if (bookIndex <= 38) return 'prophets';
  if (bookIndex <= 43) return 'gospels';
  if (bookIndex <= 64) return 'letters';
  return 'prophets';
}

